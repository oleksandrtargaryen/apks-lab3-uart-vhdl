-- Файл        : baud_gen.vhd
-- Проєкт      : Лабораторна робота №3 — UART на VHDL (варіант 1)
-- Автор       : Бартошко Олександр Ігорович, група КІ-408
--
-- Призначення : Генератор баудової швидкості (дільник тактової частоти).
--               Формує одноциклові імпульси дозволу (clock enable) `tick`
--               з частотою BAUD * OVERSAMPLE. Ці імпульси використовують
--               передавач (16 імпульсів = 1 біт) та приймач (16-кратна
--               передискретизація лінії RX).
--
--               Окремий тактовий домен НЕ створюється: увесь проєкт працює
--               від одного системного такту `clk`, а `tick` — лише сигнал
--               дозволу. Це рекомендований для ПЛІС підхід (немає похідних
--               тактів, немає проблем із тактовим деревом).
--
-- Розрахунок  : DIVISOR = round(CLK_FREQ / (BAUD * OVERSAMPLE))
--               Для 50 МГц, 115200 бод, x16:
--                 50 000 000 / (115 200 * 16) = 27.13  ->  DIVISOR = 27
--                 реальна швидкість = 50e6 / (27 * 16) = 115 740.7 бод
--                 похибка = +0.47 % (допуск UART зазвичай ±2..3 %)
--------------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity baud_gen is
    generic (
        CLK_FREQ   : positive := 50_000_000;  -- частота системного такту, Гц
        BAUD       : positive := 115_200;     -- баудова швидкість, біт/с
        OVERSAMPLE : positive := 16           -- коефіцієнт передискретизації
    );
    port (
        clk  : in  std_logic;   -- системний такт
        rst  : in  std_logic;   -- синхронне скидання, активний рівень '1'
        tick : out std_logic    -- імпульс дозволу тривалістю 1 такт clk,
                                -- період = DIVISOR тактів clk
    );
end entity baud_gen;

architecture rtl of baud_gen is

    -- Коефіцієнт ділення з округленням до найближчого цілого
    -- (додаємо половину знаменника перед цілочисельним діленням).
    constant DIVISOR : positive :=
        (CLK_FREQ + (BAUD * OVERSAMPLE) / 2) / (BAUD * OVERSAMPLE);

    -- Лічильник тактів clk у межах одного періоду tick: 0 .. DIVISOR-1
    signal cnt : natural range 0 to DIVISOR - 1 := 0;

begin

    -- Перевірка коректності параметрів на етапі елаборації.
    assert DIVISOR >= 2
        report "baud_gen: CLK_FREQ is too low for BAUD*OVERSAMPLE"
        severity failure;

    ----------------------------------------------------------------------------
    -- Лічильник-дільник: рахує 0..DIVISOR-1; на останньому значенні видає
    -- tick = '1' (рівно один такт) і повертається в 0.
    ----------------------------------------------------------------------------
    p_divider : process (clk)
    begin
        if rising_edge(clk) then
            if rst = '1' then
                cnt  <= 0;
                tick <= '0';
            elsif cnt = DIVISOR - 1 then
                cnt  <= 0;
                tick <= '1';
            else
                cnt  <= cnt + 1;
                tick <= '0';
            end if;
        end if;
    end process p_divider;

end architecture rtl;
